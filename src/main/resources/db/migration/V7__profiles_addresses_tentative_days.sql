-- Profile details shown in plans and in the profile screen.
ALTER TABLE users ADD COLUMN surname varchar(100);
ALTER TABLE users ADD COLUMN nickname varchar(30);
ALTER TABLE users ADD COLUMN phone varchar(20);
ALTER TABLE users ADD COLUMN birth_date date;
ALTER TABLE users ADD COLUMN gender varchar(20)
    CHECK (gender IN ('MALE', 'FEMALE', 'OTHER', 'PREFER_NOT_TO_SAY'));
-- Changes every time the picture changes, so clients can refresh their cached copy.
ALTER TABLE users ADD COLUMN avatar_version bigint;

-- The picture lives in its own table so loading a user never loads the image bytes.
CREATE TABLE user_avatars (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    content_type varchar(30) NOT NULL,
    data bytea NOT NULL
);

-- Named places a user starts from (home, office...). The main one is also copied to users.location,
-- which every travel estimate already uses as the default starting point.
CREATE TABLE saved_addresses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    label varchar(40) NOT NULL,
    type varchar(20) NOT NULL CHECK (type IN ('HOME', 'WORK', 'OTHER')),
    favorite boolean NOT NULL DEFAULT false,
    main boolean NOT NULL DEFAULT false,
    location_id bigint NOT NULL UNIQUE REFERENCES locations(id),
    created_at timestamp(6) NOT NULL
);
CREATE INDEX idx_saved_addresses_user ON saved_addresses(user_id);

-- Where a participant starts from for one specific plan (null = their main address).
ALTER TABLE plan_participants ADD COLUMN origin_address_id bigint REFERENCES saved_addresses(id) ON DELETE SET NULL;

-- Specific candidate days, used instead of the tentative start/end range.
CREATE TABLE plan_tentative_dates (
    plan_id bigint NOT NULL REFERENCES plans(id) ON DELETE CASCADE,
    tentative_date date NOT NULL,
    PRIMARY KEY (plan_id, tentative_date)
);

-- Keep the reference location people already saved as their first, main address.
DO $$
DECLARE
    existing record;
    copied_location bigint;
BEGIN
    FOR existing IN
        SELECT u.id AS user_id, l.latitude, l.longitude, l.address, l.district
        FROM users u JOIN locations l ON l.id = u.location_id
    LOOP
        INSERT INTO locations (latitude, longitude, address, district)
        VALUES (existing.latitude, existing.longitude, existing.address, existing.district)
        RETURNING id INTO copied_location;
        INSERT INTO saved_addresses (user_id, label, type, favorite, main, location_id, created_at)
        VALUES (existing.user_id, 'Mi ubicación', 'OTHER', true, true, copied_location, now());
    END LOOP;
END $$;
